import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';

const POSTS_DIR = path.resolve('src/content/posts');
const DIARIES_DIR = path.resolve('src/content/diaries');
const OUT_DIR = path.resolve('src/content/generated');

function generateHeadingId(text) {
  const cleanText = text.replace(/[*_`#]/g, '').trim();
  const id = cleanText
    .toLowerCase()
    .replace(/[^\w一-龥]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return id || 'section';
}

function stripDuplicateHeading(content, title) {
  if (!content) return '';
  const trimmed = content.trim();
  if (trimmed.startsWith('# ')) {
    const lines = trimmed.split('\n');
    const firstHeading = lines[0].replace(/^#\s+/, '').trim();
    if (!title || firstHeading === title.trim() || firstHeading.toLowerCase() === title.trim().toLowerCase()) {
      return lines.slice(1).join('\n').trim();
    }
  }
  return content;
}

function calculateReadingTime(content) {
  const cleanContent = content.replace(/[#*`_[\]()]/g, '').trim();
  const cjkCount = (cleanContent.match(/[一-龥]/g) || []).length;
  const nonCjkCount = (cleanContent.replace(/[一-龥]/g, ' ').match(/\b\w+\b/g) || []).length;
  const totalWords = cjkCount + nonCjkCount;
  const minutes = Math.max(1, Math.ceil(totalWords / 300));
  return { readingTime: `${minutes} 分钟`, wordCount: totalWords };
}

function extractTOC(content) {
  const lines = content.split('\n');
  const toc = [];
  let inCodeBlock = false;

  for (const line of lines) {
    if (line.trim().startsWith('```')) {
      inCodeBlock = !inCodeBlock;
      continue;
    }
    if (inCodeBlock) continue;

    const match = line.match(/^(#{1,3})\s+(.+)$/);
    if (match) {
      const level = match[1].length;
      const rawText = match[2].trim();
      const cleanText = rawText.replace(/[*_`]/g, '').trim();
      const id = generateHeadingId(cleanText);
      toc.push({ id: id || `heading-${toc.length}`, text: cleanText, level });
    }
  }
  return toc;
}

function listMdFiles(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.md'))
    .map((f) => ({
      slug: f.replace(/\.md$/, ''),
      file: path.join(dir, f),
    }))
    .sort((a, b) => a.slug.localeCompare(b.slug));
}

function buildPostMeta(slug, raw) {
  const { data, content } = matter(raw);
  const title = typeof data.title === 'string' ? data.title : slug;
  const cleanContent = stripDuplicateHeading(content, title);
  const { readingTime, wordCount } = calculateReadingTime(cleanContent);
  const toc = extractTOC(cleanContent);
  const category =
    data.category ||
    (Array.isArray(data.categories) && data.categories[0]) ||
    '技术文章';
  const coverImage =
    data.coverImage ||
    data.cover ||
    (Array.isArray(data.images) && data.images[0]) ||
    `/covers/${slug}.svg`;

  return {
    slug,
    title,
    date: data.date ? String(data.date) : new Date().toISOString().split('T')[0],
    summary:
      typeof data.summary === 'string'
        ? data.summary
        : cleanContent.slice(0, 150).replace(/[#*`_\n]/g, ' ').trim() + '...',
    tags: Array.isArray(data.tags) ? data.tags.filter((t) => typeof t === 'string') : [],
    category,
    readingTime,
    wordCount,
    toc,
    draft: Boolean(data.draft),
    coverImage,
    recommend: typeof data.recommend === 'number' ? data.recommend : 0,
  };
}

function buildDiaryMeta(slug, raw) {
  const { data, content } = matter(raw);
  const { readingTime, wordCount } = calculateReadingTime(content);

  return {
    slug,
    title: typeof data.title === 'string' ? data.title : slug,
    date: data.date ? String(data.date) : new Date().toISOString().split('T')[0],
    time: typeof data.time === 'string' ? data.time : '',
    weather: typeof data.weather === 'string' ? data.weather : '晴',
    mood: typeof data.mood === 'string' ? data.mood : '平静',
    location: typeof data.location === 'string' ? data.location : '书房',
    tags: Array.isArray(data.tags) ? data.tags.filter((t) => typeof t === 'string') : ['手记'],
    summary:
      typeof data.summary === 'string'
        ? data.summary
        : content.slice(0, 120).replace(/[#*`_\n]/g, ' ').trim() + '...',
    readingTime,
    wordCount,
    draft: data.draft === true,
    indexable: data.indexable !== false,
  };
}

function toLoaderMap(items, dirLabel) {
  const lines = [
    '// AUTO-GENERATED by scripts/generate-content-index.mjs — do not edit by hand.',
    `export const ${dirLabel}Loaders: Record<string, () => Promise<string>> = {`,
  ];
  for (const { slug } of items) {
    const rel = dirLabel === 'post' ? 'posts' : 'diaries';
    lines.push(`  '${slug}': () => import('../${rel}/${slug}.md').then((m) => (m as { default?: string }).default ?? (m as unknown as string)),`);
  }
  lines.push('};');
  lines.push('');
  return lines.join('\n');
}

function main() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  const postFiles = listMdFiles(POSTS_DIR);
  const diaryFiles = listMdFiles(DIARIES_DIR);

  const posts = postFiles
    .map(({ slug, file }) => buildPostMeta(slug, fs.readFileSync(file, 'utf-8')))
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

  const diaries = diaryFiles
    .map(({ slug, file }) => buildDiaryMeta(slug, fs.readFileSync(file, 'utf-8')))
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime());

  const index = {
    generatedAt: new Date().toISOString(),
    posts,
    diaries,
  };

  fs.writeFileSync(path.join(OUT_DIR, 'content-index.json'), JSON.stringify(index), 'utf-8');
  fs.writeFileSync(path.join(OUT_DIR, 'public-index.json'), JSON.stringify({ generatedAt: index.generatedAt, diaries: diaries.filter((diary) => !diary.draft) }), 'utf-8');

  const loaders = [
    '// AUTO-GENERATED by scripts/generate-content-index.mjs — do not edit by hand.',
    '',
    toLoaderMap(postFiles, 'post'),
    toLoaderMap(diaryFiles, 'diary'),
  ].join('\n');

  fs.writeFileSync(path.join(OUT_DIR, 'content-loaders.ts'), loaders, 'utf-8');

  console.log(
    `[content-index] Generated ${posts.length} posts + ${diaries.length} diaries metadata → src/content/generated/`
  );
}

main();
